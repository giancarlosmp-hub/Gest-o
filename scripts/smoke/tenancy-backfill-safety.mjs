import assert from "node:assert/strict";
import fs from "node:fs";

const runner = fs.readFileSync("apps/api/src/tenancy/backfillTooling.ts", "utf8");
const api = fs.readFileSync("apps/api/src/app.ts", "utf8");
const bootstrap = fs.readFileSync("apps/api/src/scripts/bootstrap.ts", "utf8");
const harness = fs.readFileSync("scripts/smoke/tenancy-backfill-postgres.sh", "utf8");
const workflow = fs.readFileSync(".github/workflows/docker-compose-ci.yml", "utf8");
for (const root of ["Client", "AgendaEvent", "Product", "AppConfig", "Goal", "ActivityKPI", "Sale", "SellerTerritoryCity", "KnowledgeDocument", "ErpSyncRun", "ErpSyncLock"]) assert.ok(runner.includes(`"${root}"`), root);
assert.doesNotMatch(runner, /tenant-default-v1|DATABASE_URL|TENANCY_MODE|DATABASE_SCHEMA_MODE/);
assert.doesNotMatch(runner, /\b(?:DELETE|DROP|TRUNCATE)\b/i);
assert.match(runner, /PRODUCTION_APPLY_NOT_IMPLEMENTED/);
assert.match(runner, /EXPLICIT_CONFIRMATION_REQUIRED/);
assert.match(runner, /APPROVED_HASH_MISMATCH/);
assert.match(runner, /UNEXPECTED_TENANT/);
assert.doesNotMatch(`${api}\n${bootstrap}`, /backfillTooling|tenancy-backfill/);
assert.doesNotMatch(harness, /\brg\b|\|\| true|DATABASE_URL/);
assert.match(harness, /docker exec -i/);
assert.match(harness, /psql -X/);
assert.match(harness, /ON_ERROR_STOP=1/);
assert.match(harness, /TENANCY_BACKFILL_TOOLING_POSTGRES=PASS/);
assert.doesNotMatch(harness, /\beval\b|\|\| true/);

const ledgerInsertStart = harness.indexOf('docker exec -i "$name" psql -X -U postgres -d backfill -v ON_ERROR_STOP=1 -v run_id="$run_id" -v approved_hash="$plan_hash"');
const negativeGateStart = harness.indexOf("step negative_gates", ledgerInsertStart);
assert.ok(ledgerInsertStart >= 0 && negativeGateStart > ledgerInsertStart, "ledger INSERT must use the guarded stdin transport before negative gates");
const ledgerBlock = harness.slice(ledgerInsertStart, negativeGateStart);
assert.match(ledgerBlock, /<<'SQL'/, "ledger SQL must use a quoted heredoc");
assert.match(ledgerBlock, /INSERT INTO ledger\(run_id,scope,state,approved_hash\)[\s\S]*:'run_id'::uuid[\s\S]*:'approved_hash'/);
assert.match(ledgerBlock, /ledger_check=\$\(docker exec -i[\s\S]*scope='all-roots'[\s\S]*state='dry_run_passed'[\s\S]*approved_hash=:'approved_hash'[\s\S]*length\(approved_hash\)=64[\s\S]*approved_hash ~ '\^\[0-9a-f\]\{64\}\$'[\s\S]*test "\$ledger_check" = 1/);
const hashValidationEnd = harness.indexOf("docker exec -i", harness.indexOf("run_id=00000000"));
const hashValidation = harness.slice(harness.indexOf("run_id=00000000"), hashValidationEnd);
assert.match(hashValidation, /\[\[ \$run_id =~ \^\[0-9a-f\]/);
assert.match(hashValidation, /\[\[ \$plan_hash =~ \^\[0-9a-f\]\{64\}\$ \]\]/);
assert.doesNotMatch(harness, /-c\s+["'][^\n]*:'(?:hash|approved_hash)'/);
assert.doesNotMatch(ledgerBlock, /INSERT INTO ledger[^\n]*\$plan_hash/);
assert.match(harness.slice(negativeGateStart), /INSERT INTO ledger VALUES \(gen_random_uuid\(\),'all-roots','planned'/, "concurrent scope rejection must remain covered");

const resumeStart = harness.indexOf("step resume_and_idempotency");
const reconciliationStart = harness.indexOf("step reconciliation", resumeStart);
assert.ok(resumeStart >= 0 && reconciliationStart > resumeStart, "idempotency proof must precede reconciliation");
const idempotencyBlock = harness.slice(resumeStart, reconciliationStart);
assert.match(idempotencyBlock, /eligible_before_reapply[\s\S]*test "\$eligible_before_reapply" = 0/);
assert.match(idempotencyBlock, /quarantine_before_reapply[\s\S]*test "\$quarantine_before_reapply" = 11/);
assert.match(idempotencyBlock, /cross_tenant_before_reapply[\s\S]*test "\$cross_tenant_before_reapply" = 0/);
assert.match(idempotencyBlock, /reapply_count=\$\(docker exec "\$name" psql -X[\s\S]*-At -v ON_ERROR_STOP=1 -c/);
assert.match(idempotencyBlock, /WITH batch AS[\s\S]*tenant_id IS NULL AND NOT invalid_reference[\s\S]*ORDER BY root,id[\s\S]*LIMIT 5[\s\S]*updated AS \([\s\S]*UPDATE root_rows[\s\S]*tenant_id IS NULL[\s\S]*RETURNING 1[\s\S]*SELECT count\(\*\) FROM updated/);
assert.match(idempotencyBlock, /test "\$reapply_count" = 0/);
assert.match(idempotencyBlock, /SELECT count\(\*\) FROM root_rows'\)" = "\$before"[\s\S]*tenant_id IS NULL AND NOT invalid_reference'\)" = 0[\s\S]*invalid_reference AND tenant_id IS NULL'\)" = 11/);
assert.doesNotMatch(idempotencyBlock, /= ''|UPDATE 0|\b(?:grep|awk)\b|\|\| true/);

const expandStepStart = workflow.indexOf("- name: Prove tenancy roots expand on PostgreSQL 16");
const backfillStepStart = workflow.indexOf("- name: Prove tenancy backfill tooling on PostgreSQL 16");
assert.ok(expandStepStart >= 0, "tenancy expand PostgreSQL gate is required");
assert.ok(backfillStepStart > expandStepStart, "backfill gate must follow tenancy expand gate");
const nextStepStart = workflow.indexOf("\n      - name:", backfillStepStart + 1);
assert.ok(nextStepStart > backfillStepStart, "backfill gate must be a bounded workflow step");
const backfillStep = workflow.slice(backfillStepStart, nextStepStart);
assert.match(backfillStep, /run:\s*npm run test:tenancy-backfill:postgres(?:\s|$)/);
assert.match(backfillStep, /API_IMAGE:\s*gest-o-api:\$\{\{ github\.sha \}\}/);
assert.doesNotMatch(backfillStep, /continue-on-error|\bif\s*:|exit\s+77|\|\||SKIP/);
console.log("tenancy backfill static safety passed");
